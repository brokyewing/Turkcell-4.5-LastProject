--   docker exec library-postgres pg_dump -U admin -d library_db --schema-only --no-owner --no-privileges
-- Yalnız book-service tabloları: authors, book_categories, books, copybooks.
-- Sıralama FK'lara uyar: authors/book_categories -> books -> copybooks.

CREATE TABLE public.authors (
    id bigint NOT NULL,
    lastname character varying(255) NOT NULL,
    name character varying(255) NOT NULL
);

ALTER TABLE public.authors ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.authors_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public.book_categories (
    id bigint NOT NULL,
    name character varying(255) NOT NULL
);

ALTER TABLE public.book_categories ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.book_categories_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public.books (
    id bigint NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    created_by character varying(255),
    updated_at timestamp(6) without time zone NOT NULL,
    updated_by character varying(255),
    available_copies integer NOT NULL,
    isbn character varying(255) NOT NULL,
    publication_date date,
    status character varying(255) NOT NULL,
    title character varying(255) NOT NULL,
    total_copies integer NOT NULL,
    author_id bigint NOT NULL,
    category_id bigint NOT NULL,
    CONSTRAINT books_status_check CHECK (((status)::text = ANY ((ARRAY['ACTIVE'::character varying, 'INACTIVE'::character varying])::text[])))
);

ALTER TABLE public.books ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.books_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public.copybooks (
    id bigint NOT NULL,
    bookid bigint NOT NULL
);

ALTER TABLE public.copybooks ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.copybooks_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

