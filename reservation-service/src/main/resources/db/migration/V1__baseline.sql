CREATE TABLE IF NOT EXISTS public.reservations (
    reservationid bigint NOT NULL,
    bookid bigint,
    copyid bigint NOT NULL,
    expire_at timestamp(6) without time zone,
    reservation_date timestamp(6) without time zone NOT NULL,
    status character varying(255) NOT NULL,
    studentid bigint NOT NULL,
    CONSTRAINT reservations_status_check CHECK (((status)::text = ANY ((ARRAY['ACTIVE'::character varying, 'CANCELLED'::character varying, 'FULFILLED'::character varying, 'EXPIRED'::character varying])::text[])))
);

